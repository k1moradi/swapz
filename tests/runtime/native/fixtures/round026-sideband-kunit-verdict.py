#!/usr/bin/env python3
"""Fail-closed verifier for ACTUALLY EXECUTED pinned Linux UML KUnit cases.

The input JSON must be generated by the original pinned Linux kunit.py
run --arch=um --json. The matching original kernel test.log must also contain
one successful KTAP event per case. A compiled object, empty suite, skipped
case, timeout, panic, duplicate, or synthetic success string is not evidence.
No kernel, module, swap, block device or memory-pressure calls are made here.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import sys
import unittest

SUITE = "swapz_round025_sideband_compiler_only"
CASES = frozenset((
    "swapz_ci_clone_lifetime_kunit",
    "swapz_ci_split_lifetime_kunit",
    "swapz_ci_reuse_and_abort_kunit",
    "swapz_ci_reject_invalid_kunit",
    "swapz_ci_invalid_clone_kunit",
    "swapz_ci_reuse_private_kunit",
    "swapz_ci_abort_dead_ref_kunit",
))
MAX_RESULT_BYTES = 512 * 1024
MAX_LOG_BYTES = 2 * 1024 * 1024
KERNEL_TIMESTAMP = re.compile(r"^\[\s*[0-9]+\.[0-9]+\]\s*")
KTAP_CASE = re.compile(r"^ok\s+[0-9]+\s+(?:-\s+)?([A-Za-z0-9_]+)(?:\s+#.*)?$")


class QualificationRefusal(ValueError):
    """First source-bound KUnit qualification failure, not a live verdict."""


def _source_contents(path: Path, max_size: int) -> str:
    if not path.is_file() or path.is_symlink():
        raise QualificationRefusal("evidence_missing_or_symlink")
    file_size = path.stat().st_size
    if not 1 <= file_size <= max_size:
        raise QualificationRefusal("evidence_file_size")
    try:
        return path.read_text(encoding="utf-8")
    except (OSError, UnicodeError) as error:
        raise QualificationRefusal("evidence_unreadable") from error


def verify_executed_kunit_json(document: object, kernel_log: str) -> None:
    if not isinstance(document, dict) or document.get("arch") != "um":
        raise QualificationRefusal("not_pinned_uml_execution")
    if not isinstance(kernel_log, str) or "KTAP version 1" not in kernel_log:
        raise QualificationRefusal("missing_kernel_ktap")
    if re.search(r"(?:Kernel panic|BUG: KASAN|KASAN:|UBSAN:|Oops:)",
                 kernel_log, flags=re.IGNORECASE):
        raise QualificationRefusal("kernel_panic_or_sanitizer")

    # Inspect the actual original KUnit parser's nested JSON tree. The
    # suite name must be unique; never accept a separately printed PASS.
    pending = [document]
    matches: list[dict] = []
    visited = 0
    while pending:
        group = pending.pop()
        visited += 1
        if visited > 1000 or not isinstance(group, dict):
            raise QualificationRefusal("invalid_kunit_result_tree")
        if group.get("name") == SUITE:
            matches.append(group)
        children = group.get("sub_groups", [])
        if not isinstance(children, list) or len(children) > 200:
            raise QualificationRefusal("invalid_kunit_group_children")
        pending.extend(children)
    if len(matches) != 1:
        raise QualificationRefusal("missing_or_duplicate_executed_suite")

    suite = matches[0]
    actual_cases = suite.get("test_cases")
    if (not isinstance(actual_cases, list) or
            len(actual_cases) != len(CASES)):
        raise QualificationRefusal("missing_or_extra_kunit_case")
    seen: set[str] = set()
    for case in actual_cases:
        if not isinstance(case, dict):
            raise QualificationRefusal("invalid_kunit_case")
        name, status = case.get("name"), case.get("status")
        if name not in CASES or name in seen:
            raise QualificationRefusal("unexpected_or_duplicate_kunit_case")
        seen.add(name)
        if status != "PASS":
            raise QualificationRefusal(f"kunit_case_not_passed:{name}")
    if seen != CASES:
        raise QualificationRefusal("incomplete_kunit_case_set")

    counts = suite.get("misc")
    if not isinstance(counts, dict):
        raise QualificationRefusal("missing_kunit_execution_counts")
    for key, expected in {
        "tests": len(CASES), "passed": len(CASES), "failed": 0,
        "crashed": 0, "skipped": 0, "errors": 0,
    }.items():
        value = counts.get(key)
        if type(value) is not int or value != expected:
            raise QualificationRefusal(f"kunit_count_mismatch:{key}")

    # Pinned lib/kunit/test.c prints "%s %zd %s" without a hyphen;
    # pinned upstream kunit_parser.TEST_RESULT accepts an optional "-".
    # Match that grammar, but require exact counted case identities.
    kernel_cases: dict[str, int] = {}
    for line in kernel_log.splitlines():
        clean_line = KERNEL_TIMESTAMP.sub("", line).strip()
        match = KTAP_CASE.fullmatch(clean_line)
        if match:
            case_name = match.group(1)
            kernel_cases[case_name] = kernel_cases.get(case_name, 0) + 1
    for name in CASES:
        if kernel_cases.get(name) != 1:
            raise QualificationRefusal(f"missing_or_duplicate_kernel_case:{name}")
    # The second, independent trace must have the exact same 7 case events.
    if set(kernel_cases) & CASES != CASES:
        raise QualificationRefusal("kernel_case_trace_incomplete")


def validate_files(result_path: Path, log_path: Path) -> None:
    try:
        source_result = _source_contents(result_path, MAX_RESULT_BYTES)
        kernel_log = _source_contents(log_path, MAX_LOG_BYTES)
        document = json.loads(source_result)
    except (json.JSONDecodeError, UnicodeError) as error:
        raise QualificationRefusal("kunit_json_parse") from error
    verify_executed_kunit_json(document, kernel_log)


def sample_evidence() -> tuple[dict, str]:
    cases = sorted(CASES)
    document = {
        "name": "KUnit Test Group", "arch": "um",
        "sub_groups": [{
            "name": SUITE, "sub_groups": [],
            "test_cases": [{"name": name, "status": "PASS"} for name in cases],
            "misc": {
                "tests": len(cases), "passed": len(cases),
                "failed": 0, "crashed": 0, "skipped": 0, "errors": 0,
            },
        }],
    }
    log = ("[    0.001] KTAP version 1\n"
           "[    0.002] # Subtest: " + SUITE + "\n" +
           "\n".join(f"[    0.003]     ok {i} {name}"
                     for i, name in enumerate(cases, 1)) + "\n")
    return document, log


class ExecutedKunitVerifierSelfTest(unittest.TestCase):
    def test_genuine_result_shape_passes(self) -> None:
        parsed, output = sample_evidence()
        verify_executed_kunit_json(parsed, output)

    def test_every_source_or_ktap_forgery_refuses(self) -> None:
        import copy
        sample, log = sample_evidence()
        variants: list[tuple[object, str]] = []
        for mutated in ("SKIP", "FAIL", "ERROR"):
            document = copy.deepcopy(sample)
            document["sub_groups"][0]["test_cases"][0]["status"] = mutated
            variants.append((document, log))
        for field, value in (
            ("tests", 0), ("passed", 6), ("failed", 1),
            ("crashed", 1), ("skipped", 1), ("errors", 1),
        ):
            document = copy.deepcopy(sample)
            document["sub_groups"][0]["misc"][field] = value
            variants.append((document, log))
        for changed in (
            "",
            "KUnit suite compiled but not executed\n",
            log.replace("KTAP version 1", "TAP version 14"),
            log.replace("ok 1 ", "not ok 1 ", 1),
            log + "Kernel panic - not syncing\n",
            log + "BUG: KASAN: use-after-free\n",
            log + "UBSAN: shift-out-of-bounds\n",
            log + next(line for line in log.splitlines()
                       if "ok 1 " in line) + "\n",
        ):
            variants.append((copy.deepcopy(sample), changed))
        document = copy.deepcopy(sample)
        document["arch"] = "x86_64"
        variants.append((document, log))
        document = copy.deepcopy(sample)
        document["sub_groups"] = []
        variants.append((document, log))
        document = copy.deepcopy(sample)
        document["sub_groups"].append(copy.deepcopy(document["sub_groups"][0]))
        variants.append((document, log))
        document = copy.deepcopy(sample)
        document["sub_groups"][0]["test_cases"].append(
            copy.deepcopy(document["sub_groups"][0]["test_cases"][0]))
        variants.append((document, log))
        document = copy.deepcopy(sample)
        document["sub_groups"][0]["test_cases"][0]["name"] = "fabricated"
        variants.append((document, log))
        document = copy.deepcopy(sample)
        document["sub_groups"][0]["misc"]["passed"] = True
        variants.append((document, log))
        for index, (document, output) in enumerate(variants):
            with self.subTest(mutation=index):
                with self.assertRaises(QualificationRefusal):
                    verify_executed_kunit_json(document, output)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--self-test", action="store_true")
    parser.add_argument("--result", type=Path)
    parser.add_argument("--kernel-log", type=Path)
    arguments = parser.parse_args()

    if arguments.self_test:
        suite = unittest.defaultTestLoader.loadTestsFromTestCase(
            ExecutedKunitVerifierSelfTest)
        result = unittest.TextTestRunner(verbosity=2).run(suite)
        return 0 if result.wasSuccessful() else 1
    if not arguments.result or not arguments.kernel_log:
        parser.error("--result and --kernel-log are required for actual KUnit")
    try:
        validate_files(arguments.result, arguments.kernel_log)
    except (OSError, QualificationRefusal) as error:
        print(f"ROUND026_UML_KUNIT_BLOCKED first_cause={error}")
        print("KUNIT_EXECUTED=NOT_QUALIFIED LOADED_4096=NOT_RUN "
              "PHYSICAL=NOT_RUN DIRECT_COMPRESSED=DISABLED")
        return 2
    print(f"ROUND026_UML_KUNIT_EXECUTED_PASS suite={SUITE} "
          f"cases={len(CASES)} arch=um")
    print("KUNIT_EXECUTED=PASS SOURCE_ONLY=PASS LOADED_4096=NOT_RUN "
          "PHYSICAL=NOT_RUN DIRECT_COMPRESSED=DISABLED")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
